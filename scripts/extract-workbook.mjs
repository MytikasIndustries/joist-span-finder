// Reads the text export of Eric's workbook
// (ClarkDietrich_Floor_Joist_Span_Limits_Mytikas_Profiles_v2.xlsx) and writes:
//   src/data.js                     the span tables the app uses
//   data/floor-joist-spans.csv      the same 1,620 values, one per row, for people
//   data/check/all-data-rows.tsv    rows from the workbook's own "All Data" tab, used by the tests
//
// Usage: node scripts/extract-workbook.mjs
// When the workbook changes, replace the two files in data/source/ with fresh
// exports and run this again, then `npm test`.

import { readFileSync, writeFileSync } from 'node:fs';

const SHEETS = 'data/source/workbook-v2-sheets-1-11.txt';
const ALL_DATA = 'data/source/workbook-v2-all-data-partial.txt';

// Column order on every load-case tab, left to right.
const COLUMNS = [];
for (const deflection of ['L/360', 'L/480'])
  for (const condition of ['single', 'two'])
    for (const spacing of [12, 16, 24]) COLUMNS.push({ deflection, condition, spacing });

const MEMBER = /^(\d{3,4})S200-(\d{2})$/;
const SPAN = /^(\d+)' (\d+)"(?: ([eia]))?$/;

function parseSpan(text) {
  const m = SPAN.exec(text.trim());
  if (!m) throw new Error(`Unreadable span "${text}"`);
  const inches = Number(m[1]) * 12 + Number(m[2]);
  return m[3] ? `${inches}${m[3]}` : String(inches);
}

const lines = readFileSync(SHEETS, 'utf8').split('\n');
const tables = [];
let current = null;
for (const line of lines) {
  const sheet = /^## Sheet: (\d+)DL-(\d+)LL /.exec(line);
  if (sheet) {
    current = { dl: Number(sheet[1]), ll: Number(sheet[2]), pages: '', rows: {} };
    tables.push(current);
    continue;
  }
  if (line.startsWith('## Sheet:')) {
    current = null;
    continue;
  }
  if (!current) continue;
  const pages = /pp\. (\d+)–(\d+)/.exec(line);
  if (pages && !current.pages) current.pages = `${pages[1]}–${pages[2]}`;
  const cells = line.split('\t');
  if (!MEMBER.test(cells[0])) continue;
  if (cells[2] !== '50') throw new Error(`${cells[0]}: expected Fy 50, got ${cells[2]}`);
  const values = cells.slice(3, 15).map(parseSpan);
  if (values.length !== 12) throw new Error(`${cells[0]}: expected 12 spans`);
  current.rows[cells[0]] = values;
}

if (tables.length !== 9) throw new Error(`Expected 9 load cases, found ${tables.length}`);
for (const t of tables) {
  const n = Object.keys(t.rows).length;
  if (n !== 15) throw new Error(`${t.dl}/${t.ll}: expected 15 members, found ${n}`);
  if (!t.pages) throw new Error(`${t.dl}/${t.ll}: no source pages`);
}

const header = `// Generated by scripts/extract-workbook.mjs from Eric Bonick's workbook
// "ClarkDietrich Floor Joist Span Limits, Mytikas Profiles v2" (10/23/2026).
// Do not edit by hand. Each span is total inches, with the web stiffener
// code appended when the table shows one (e = end supports, i = interior
// support, a = all supports). Column order: ${COLUMNS.map((c) => `${c.deflection} ${c.condition} ${c.spacing}`).join(', ')}.
`;
writeFileSync(
  'src/data.js',
  `${header}export const SPAN_TABLES = ${JSON.stringify(tables, null, 1)};\n`,
);

const csv = ['dead_load_psf,live_load_psf,live_load_deflection,span_condition,spacing_in_oc,member,allowable_span_in,web_stiffener_code,guide_pages'];
for (const t of tables)
  for (const [member, values] of Object.entries(t.rows))
    values.forEach((v, i) => {
      const c = COLUMNS[i];
      const code = /[eia]$/.test(v) ? v.slice(-1) : '';
      csv.push([t.dl, t.ll, c.deflection, c.condition, c.spacing, member, parseInt(v, 10), code, t.pages].join(','));
    });
writeFileSync('data/floor-joist-spans.csv', csv.join('\n') + '\n');

// The All Data tab is an independent listing inside the same workbook; keep
// the rows the export carried so the tests can cross-check against them.
const allData = readFileSync(ALL_DATA, 'utf8')
  .split('\n')
  .filter((l) => /^\d+ psf DL \/ \d+ psf LL\t/.test(l))
  .map((l) => {
    const c = l.split('\t');
    // dl, ll, deflection, condition, spacing, member, total inches, stiffener code
    return [c[1], c[2], c[4], c[5], c[6], c[7], c[16], c[18] ?? ''].join('\t');
  });
writeFileSync('data/check/all-data-rows.tsv', allData.join('\n') + '\n');

console.log(`Wrote ${csv.length - 1} spans from ${tables.length} load cases; ${allData.length} All Data rows kept for checks.`);
